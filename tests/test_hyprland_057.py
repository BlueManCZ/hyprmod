class TestLegacyRecovery:
    def test_057_autogenerated_lua_with_conf_needs_recovery(self, hypr_057) -> None:
        assert config.legacy_config_recovery_needed() is True

    def test_057_custom_lua_does_not_need_recovery(self, hypr_057) -> None:
        hypr_057.lua.write_text("hl.config({ general = { gaps_in = 4 } })\n")
        assert config.legacy_config_recovery_needed() is False

    def test_057_missing_lua_with_conf_needs_recovery(self, hypr_057) -> None:
        hypr_057.lua.unlink()
        assert config.legacy_config_recovery_needed() is True

    def test_056_never_needs_recovery(self, hypr_056) -> None:
        assert config.legacy_config_recovery_needed() is False

    def test_057_without_conf_does_not_need_recovery(self, hypr_057) -> None:
        hypr_057.conf.unlink()
        assert config.legacy_config_recovery_needed() is False

    def test_recovery_replaces_placeholder_and_adds_include(self, hypr_057) -> None:
        managed = hypr_057.dir / "hyprland-gui.lua"
        with config.managed_path_override(managed):
            plan = analyze_conversion(hypr_057.conf)
            assert hypr_057.lua in plan.existing_lua
            execute_conversion(plan, overwrite=True)

            assert "autogenerated" not in hypr_057.lua.read_text()
            assert "gaps_in = 5" in hypr_057.lua.read_text()
            assert needs_setup() is True
            run_setup()

        assert 'require("hyprland-gui")' in hypr_057.lua.read_text()
        assert managed.exists()


