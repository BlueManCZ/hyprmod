class TestLuaRequired:
    def test_057_requires_lua(self, hypr_057) -> None:
        assert config.lua_is_required() is True
        assert config.is_lua_mode() is True

    def test_057_is_lua_even_without_file(self, tmp_path, monkeypatch) -> None:
        hypr_dir = tmp_path / "hypr"
        hypr_dir.mkdir()
        monkeypatch.setattr("hyprland_config.default_config_dir", lambda: hypr_dir)
        config.configure_runtime(provider=None, version="0.57.0")
        assert config.is_lua_mode() is True
        assert config.managed_path().suffix == ".lua"

    def test_056_keeps_file_based_mode(self, hypr_056) -> None:
        assert config.lua_is_required() is False
        assert config.is_lua_mode() is False
        assert config.managed_path().suffix == ".conf"

    def test_configure_runtime_invalidates_mode_cache(self, hypr_057) -> None:
        assert config.is_lua_mode() is True
        config.configure_runtime(provider="hyprlang", version="0.56.0")
        assert config.is_lua_mode() is False


class TestManagedPath:
    def test_057_repoints_explicit_conf_to_lua(self, hypr_057) -> None:
        target = hypr_057.dir / "managed.conf"
        with config.managed_path_override(target):
            assert config.managed_path() == target.with_suffix(".lua")

    def test_057_write_all_never_creates_conf(self, hypr_057) -> None:
        target = hypr_057.dir / "managed.conf"
        with config.managed_path_override(target):
            config.write_all({"general:gaps_in": "5"}, config.ConfigSections())
        assert target.with_suffix(".lua").exists()
        assert not target.exists()

    def test_set_managed_path_forces_lua(self, hypr_057) -> None:
        try:
            config.set_managed_path(hypr_057.dir / "managed.conf")
            assert config.managed_path().suffix == ".lua"
        finally:
            config.set_managed_path(None)

    def test_056_explicit_conf_stays_conf(self, hypr_056) -> None:
        target = hypr_056.dir / "managed.conf"
        with config.managed_path_override(target):
            assert config.managed_path() == target


