class TestExplicitEntrypoint:
    def test_hyprland_config_env_is_used(self, tmp_path, monkeypatch) -> None:
        explicit = tmp_path / "custom.lua"
        explicit.write_text("-- custom\n")
        monkeypatch.setenv("HYPRLAND_CONFIG", str(explicit))
        config.configure_runtime(provider=None, version=None)
        assert config.user_entry_path() == explicit
        assert config.is_lua_mode() is True

    def test_explicit_conf_is_the_legacy_entrypoint(self, tmp_path, monkeypatch) -> None:
        explicit = tmp_path / "custom.conf"
        explicit.write_text("general {\n  gaps_in = 5\n}\n")
        monkeypatch.setenv("HYPRLAND_CONFIG", str(explicit))
        config.configure_runtime(provider=None, version=None)
        assert config.legacy_entry_path() == explicit
